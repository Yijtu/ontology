#!/usr/bin/env node
// Canonical JSON Schema -> TypeScript generator.
//
// Source of truth: packages/contracts/schema/*.schema.json (draft 2020-12) plus the
// two canonical data documents (tool-catalog.json, error-catalog.json).
//
// Usage:
//   node scripts/generate-contracts.mjs           # write src/generated/**
//   node scripts/generate-contracts.mjs --check   # fail if committed output differs
//
// The --check mode is what proves schema<->type consistency in CI: it regenerates the
// committed artifacts in memory and byte-compares them.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const HERE = dirname(fileURLToPath(import.meta.url))
const PACKAGE_ROOT = resolve(HERE, '..')
const SCHEMA_DIR = join(PACKAGE_ROOT, 'schema')
const OUT_DIR = join(PACKAGE_ROOT, 'src', 'generated')

const CONTRACT_VERSION = '0.2.0'
const SCHEMA_DRAFT = 'https://json-schema.org/draft/2020-12/schema'
const ROOT_SCHEMA_ID = 'https://ontology.local/schema/contracts.schema.json'
const SCHEMA_BASE_URI = 'https://ontology.local/schema'

const GENERATED_HEADER = [
  '/* AUTO-GENERATED by packages/contracts/scripts/generate-contracts.mjs -- DO NOT EDIT. */',
  '/* Source of truth: packages/contracts/schema/  |  Regenerate: pnpm --filter @ontology/contracts run generate:contracts */',
  '',
].join('\n')

const CROSS_FILE_REF = /^\.\/([a-z0-9-]+)\.schema\.json#\/\$defs\/([A-Za-z0-9_]+)$/

const checkOnly = process.argv.includes('--check')

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map((child) => rewriteRefs(child))
  if (node === null || typeof node !== 'object') return node

  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string') {
      const match = CROSS_FILE_REF.exec(value)
      out[key] = match ? `#/$defs/${match[2]}` : value
    } else {
      out[key] = rewriteRefs(value)
    }
  }
  return out
}

function loadSchemaDocuments() {
  return readdirSync(SCHEMA_DIR)
    .filter((name) => name.endsWith('.schema.json'))
    .sort()
    .map((name) => ({ name, doc: readJson(join(SCHEMA_DIR, name)) }))
}

function buildDefinitions(documents) {
  const defs = {}
  for (const { name, doc } of documents) {
    const source = doc.$defs ?? {}
    for (const [defName, def] of Object.entries(source)) {
      if (Object.prototype.hasOwnProperty.call(defs, defName)) {
        throw new Error(`duplicate $defs name "${defName}" while merging ${name}`)
      }
      defs[defName] = rewriteRefs(def)
    }
  }
  return defs
}

function resolveDefRef(defs, ref) {
  const match = typeof ref === 'string' ? CROSS_FILE_REF.exec(ref) : null
  if (!match) throw new Error(`unsupported $ref in canonical data: ${String(ref)}`)
  const target = defs[match[2]]
  if (target === undefined) throw new Error(`$ref target not found: ${match[2]}`)
  return target
}

// The tool catalogue keeps named `$ref`s instead of inlining schemas, but rewrites them
// to the absolute `$id` form so a consumer can register SCHEMA_DOCUMENTS with ajv and
// compile the tool schema without any file-system resolution.
function toAbsoluteRef(ref) {
  const match = typeof ref === 'string' ? CROSS_FILE_REF.exec(ref) : null
  if (!match) throw new Error(`unsupported $ref in tool catalogue: ${String(ref)}`)
  return `${SCHEMA_BASE_URI}/${match[1]}.schema.json#/$defs/${match[2]}`
}

async function renderContractsTypes(defs) {
  const root = {
    $schema: SCHEMA_DRAFT,
    $id: ROOT_SCHEMA_ID,
    title: 'OntologyContracts',
    description: `Canonical cross-process contract set, version ${CONTRACT_VERSION}.`,
    type: 'object',
    additionalProperties: false,
    required: ['contractVersion'],
    properties: {
      contractVersion: { const: CONTRACT_VERSION },
    },
    $defs: defs,
  }

  return compile(root, 'OntologyContracts', {
    cwd: SCHEMA_DIR,
    bannerComment: GENERATED_HEADER,
    // Schemas that need strictness set `additionalProperties: false` explicitly; a bare
    // `type: object` (arbitrary JSON payloads such as inputSchema) becomes an index
    // signature instead of the unsound `{}` type.
    additionalProperties: true,
    unreachableDefinitions: true,
    unknownAny: true,
    strictIndexSignatures: true,
    ignoreMinAndMaxItems: true,
    maxItems: -1,
    format: true,
    style: {
      semi: false,
      singleQuote: true,
      printWidth: 100,
      trailingComma: 'none',
    },
  })
}

function renderToolCatalogue(defs) {
  const catalogue = readJson(join(SCHEMA_DIR, 'tool-catalog.json'))
  const controllerServiceDef = defs.ControllerServiceId
  const controllerServiceIds = Array.isArray(controllerServiceDef?.enum)
    ? controllerServiceDef.enum
    : []
  if (controllerServiceIds.length === 0) {
    throw new Error('ControllerServiceId enum is missing from tools.schema.json')
  }

  const tools = catalogue.tools.map((tool) => {
    if (tool.inputSchema?.$ref !== undefined) {
      resolveDefRef(defs, tool.inputSchema.$ref)
    }
    if (tool.outputSchema?.$ref !== undefined) {
      resolveDefRef(defs, tool.outputSchema.$ref)
    }
    return {
      toolId: tool.toolId,
      version: tool.version,
      inputSchema: { $ref: toAbsoluteRef(tool.inputSchema?.$ref) },
      outputSchema: { $ref: toAbsoluteRef(tool.outputSchema?.$ref) },
      requiredCapabilities: tool.requiredCapabilities,
      readOnly: tool.readOnly,
      resultLimits: tool.resultLimits,
    }
  })

  return [
    GENERATED_HEADER,
    "import type { ToolDefinition, ToolId } from './contracts'",
    '',
    `export const TOOL_CATALOGUE_VERSION = ${JSON.stringify(catalogue.catalogueVersion)}`,
    '',
    `export const TOOL_CATALOGUE: readonly ToolDefinition[] = ${JSON.stringify(tools, null, 2)}`,
    '',
    'export const TOOL_IDS: readonly ToolId[] = TOOL_CATALOGUE.map((tool) => tool.toolId)',
    '',
    `export const CONTROLLER_SERVICE_IDS = ${JSON.stringify(controllerServiceIds)} as const`,
    '',
  ].join('\n')
}

function renderErrorCatalogue() {
  const catalogue = readJson(join(SCHEMA_DIR, 'error-catalog.json'))

  return [
    GENERATED_HEADER,
    "import type { ErrorCode, ErrorDescriptor } from './contracts'",
    '',
    `export const ERROR_CATALOGUE_VERSION = ${JSON.stringify(catalogue.catalogVersion)}`,
    '',
    `export const ERROR_CATALOG: Readonly<Record<ErrorCode, ErrorDescriptor>> = ${JSON.stringify(catalogue.catalog, null, 2)}`,
    '',
    'export const ERROR_CODES: readonly ErrorCode[] = Object.keys(ERROR_CATALOG) as ErrorCode[]',
    '',
  ].join('\n')
}

function renderSchemaBundle(documents) {
  return [
    GENERATED_HEADER,
    'export type JsonSchemaObject = { [key: string]: unknown }',
    '',
    'export const CONTRACT_VERSION = ' + JSON.stringify(CONTRACT_VERSION),
    '',
    'export const SCHEMA_DOCUMENTS: readonly JsonSchemaObject[] = ' +
      JSON.stringify(
        documents.map(({ doc }) => doc),
        null,
        2,
      ),
    '',
    'export const SCHEMA_DOCUMENT_BY_ID: Readonly<Record<string, JsonSchemaObject>> = Object.fromEntries(',
    '  SCHEMA_DOCUMENTS.flatMap((doc) => (typeof doc.$id === \u0027string\u0027 ? [[doc.$id, doc] as const] : [])),',
    ')',
    '',
  ].join('\n')
}

async function main() {
  const documents = loadSchemaDocuments()
  if (documents.length === 0) throw new Error(`no *.schema.json found in ${SCHEMA_DIR}`)

  const defs = buildDefinitions(documents)

  const outputs = [
    ['contracts.ts', await renderContractsTypes(defs)],
    ['tool-catalogue.ts', renderToolCatalogue(defs)],
    ['error-catalogue.ts', renderErrorCatalogue()],
    ['schema-bundle.ts', renderSchemaBundle(documents)],
  ]

  if (checkOnly) {
    const drifted = outputs.filter(([name, content]) => {
      let committed
      try {
        committed = readFileSync(join(OUT_DIR, name), 'utf8')
      } catch {
        return true
      }
      // Normalize line endings: the generated output is always LF, but a Windows
      // checkout with core.autocrlf=true may present CRLF in the working tree.
      return committed.replace(/\r\n/g, '\n') !== content
    })

    if (drifted.length > 0) {
      process.stderr.write(
        `Generated contracts are stale: ${drifted.map(([name]) => name).join(', ')}\n` +
          'Run `pnpm --filter @ontology/contracts run generate:contracts` and commit the result.\n',
      )
      process.exitCode = 1
      return
    }

    process.stdout.write('Generated contracts match the canonical JSON Schema.\n')
    return
  }

  mkdirSync(OUT_DIR, { recursive: true })
  for (const [name, content] of outputs) {
    writeFileSync(join(OUT_DIR, name), content, 'utf8')
  }
  process.stdout.write(`Wrote ${outputs.length} files to ${OUT_DIR}\n`)
}

await main()
